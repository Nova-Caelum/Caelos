import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, readdirSync, realpathSync, renameSync } from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
if (!process.argv[2]) throw new Error("Provide the React 19 UI package directory");
const source = realpathSync(resolve(process.argv[2]));
const stage = realpathSync(join(root, "staging/foundry-react19"));
if (!source.includes("/NovaCaelum_code/") || !stage.includes("/NovaCaelum_code/")) throw new Error("Use verified code checkouts outside the vault");
const pkg = JSON.parse(readFileSync(join(source, "package.json")));
if (pkg.name !== "@nova-caelum/ui" || !pkg.peerDependencies.react.startsWith("^19")) throw new Error("Expected the React 19 UI candidate");
execFileSync("corepack", ["pnpm", "run", "build"], { cwd: source, stdio: "inherit" });
const vendor = join(stage, "vendor");
const packed = JSON.parse(execFileSync("npm", ["pack", "--ignore-scripts", "--json", "--pack-destination", vendor], { cwd: source, encoding: "utf8" }))[0];
const hash = data => createHash("sha256").update(data).digest("hex");
const sha256 = hash(readFileSync(join(vendor, packed.filename)));
const filename = `nova-caelum-ui-${sha256.slice(0, 16)}.tgz`;
renameSync(join(vendor, packed.filename), join(vendor, filename));
const sourceFiles = {};
function walk(dir) { for (const ent of readdirSync(join(source, dir), { withFileTypes: true })) { const rel = `${dir}/${ent.name}`; if (ent.isDirectory()) walk(rel); else sourceFiles[rel] = hash(readFileSync(join(source, rel))); } }
walk("src");
for (const file of ["package.json", "panda.config.ts", "tsup.config.ts", "tsconfig.json"]) sourceFiles[file] = hash(readFileSync(join(source, file)));
writeFileSync(join(stage, "snapshot.json"), JSON.stringify({ source: "caelos-chat-react19/packages/ui", version: pkg.version, capturedAt: new Date().toISOString(), archive: `vendor/${filename}`, sha256, sourceFiles }, null, 2) + "\n");
const manifestPath = join(stage, "package.json");
const manifest = JSON.parse(readFileSync(manifestPath));
manifest.dependencies["@nova-caelum/ui"] = `file:vendor/${filename}`;
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
console.log(`Snapshot captured: ${filename}. Install staging dependencies to update its lockfile, then build and review.`);
